describe('read optimization barriers', () => {
	it.each(unsafe)('%s', async (_name, body) => {
		const source = `function run() { ${body} }`;
		const code = optimize(source);
		expect(code).toBe(generate(parse(source)).code);
		expect(await execute(code)).toEqual(await execute(source));
	});
	it('forgets facts across suspension', async () => {
		const source =
			'async function run() { const object = {x: 1}; const first = object.x; await Promise.resolve().then(() => { object.x = 2; }); const second = object.x; return [first, second]; }';
		const code = optimize(source);
		expect(code).toBe(generate(parse(source)).code);
		expect(await execute(code)).toEqual(await execute(source));
	});
});
