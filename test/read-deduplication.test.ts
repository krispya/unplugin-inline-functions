describe('safe read deduplication', () => {
	it.each(safe)('%s', async (_name, body) => {
		const source = `function run() { ${body} }`;
		const code = optimize(source);
		expect(code).toContain('second = first');
		expect(await execute(code)).toEqual(await execute(source));
	});
	it('optimizes within a branch without lifting reads out of it', async () => {
		const source =
			'function run() { if (true) { const object = {x: 1}; const first = object.x; const second = object.x; return [first, second]; } }';
		const code = optimize(source);
		expect(code).toContain('second = first');
		expect(await execute(code)).toEqual(await execute(source));
	});
	it('carries allocation proof into an invocation block without carrying cached reads', async () => {
		const source =
			'function run() { const object = {x: 1}; frame: { const arg = (0, object); let local = arg; const first = local.x; const second = local.x; return [first, second]; } }';
		const code = optimize(source);
		expect(code).toContain('second = first');
		expect(await execute(code)).toEqual(await execute(source));
	});
	it('uses one read in the actual inlining pipeline', async () => {
		const source =
			'/* @inline */ function read(object) { return object.x; } function run() { const object = {x: 1}; const first = read(object); const second = read(object); return [first, second]; }';
		const ast = parse(source, { sourceFilename: '/test/read.js' });
		resetMetadata();
		collectMetadata(ast);
		const code = inlineFunctions(ast);
		expect(code).toContain('const second = first');
		expect(code).not.toContain('= read(object)');
		expect(await execute(code)).toEqual(await execute(source));
	});
	it('deduplicates reads inside an expanded invocation frame', async () => {
		const source =
			'/* @inline */ function read(object) { const first = object.x; const second = object.x; return first + second; } function run() { const object = {x: 2}; return read(object); }';
		const ast = parse(source, { sourceFilename: '/test/read-frame.js' });
		resetMetadata();
		collectMetadata(ast);
		const code = inlineFunctions(ast);
		expect(code).toMatch(/const _second\w* = _first\w*;/);
		expect(await execute(code)).toEqual(await execute(source));
	});
});

